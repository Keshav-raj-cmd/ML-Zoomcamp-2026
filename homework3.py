import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.metrics import mutual_info_score
from sklearn.feature_extraction import DictVectorizer
from sklearn.linear_model import LogisticRegression

"""## Data Preparation
- Check for missing values.
- Categorical features missing values -> replaced with 'NA'.
- Numerical features missing values -> replaced with 0.0.
"""

df = pd.read_csv('/content/course_lead_scoring_2026.csv')

# Identify categorical and numerical columns
categorical = list(df.select_dtypes(include=['object']).columns)
numerical = list(df.select_dtypes(exclude=['object']).columns)

# Remove target variable 'converted' from standard features list
if 'converted' in numerical:
    numerical.remove('converted')
elif 'converted' in categorical:
    categorical.remove('converted')

# Fill missing values
for col in categorical:
    df[col] = df[col].fillna('NA')

for col in numerical:
    df[col] = df[col].fillna(0.0)

print("Missing values after cleaning:")
print(df.isnull().sum().sum())
display(df.head())

"""## Question 1: Most frequent observation (mode) for the column `industry`"""

mode_industry = df['industry'].mode()[0]
print(f"The most frequent industry (mode) is: {mode_industry}")

"""## Question 2: Correlation Matrix for Numerical Features"""

corr_matrix = df[numerical].corr()
display(corr_matrix)

# Check specified pairs
pairs = [
    ('interaction_count', 'lead_score'),
    ('number_of_courses_viewed', 'lead_score'),
    ('number_of_courses_viewed', 'interaction_count'),
    ('annual_income', 'interaction_count')
]

for p1, p2 in pairs:
    if p1 in corr_matrix.columns and p2 in corr_matrix.columns:
        print(f"Correlation between {p1} and {p2}: {corr_matrix.loc[p1, p2]:.4f}")

"""## Split the data"""

df_full_train, df_test = train_test_split(df, test_size=0.2, random_state=42)
df_train, df_val = train_test_split(df_full_train, test_size=0.25, random_state=42)

y_train = df_train['converted'].values
y_val = df_val['converted'].values
y_test = df_test['converted'].values

del df_train['converted']
del df_val['converted']
del df_test['converted']

print(f"Train size: {len(df_train)}, Val size: {len(df_val)}, Test size: {len(df_test)}")

"""## Question 3: Mutual Information Score with Target"""

def mutual_info_converted_score(series):
    return mutual_info_score(series, y_train)

mi = df_train[categorical].apply(mutual_info_converted_score)
mi = mi.round(2).sort_values(ascending=False)
print("Mutual Information Scores:")
print(mi)

"""## Question 4: Logistic Regression & Accuracy"""

train_dicts = df_train[categorical + numerical].to_dict(orient='records')
dv = DictVectorizer(sparse=False)
X_train = dv.fit_transform(train_dicts)

val_dicts = df_val[categorical + numerical].to_dict(orient='records')
X_val = dv.transform(val_dicts)

model = LogisticRegression(solver='liblinear', C=1.0, max_iter=1000, random_state=42)
model.fit(X_train, y_train)

val_preds = model.predict(X_val)
original_accuracy = (val_preds == y_val).mean()
print(f"Validation accuracy: {original_accuracy:.4f} (Rounded: {round(original_accuracy, 2)})")

"""## Question 5: Feature Elimination"""

all_features = categorical + numerical

for feature in ['lead_source', 'number_of_courses_viewed', 'interaction_count']:
    subset_features = [f for f in all_features if f != feature]

    train_dicts_sub = df_train[subset_features].to_dict(orient='records')
    val_dicts_sub = df_val[subset_features].to_dict(orient='records')

    dv_sub = DictVectorizer(sparse=False)
    X_train_sub = dv_sub.fit_transform(train_dicts_sub)
    X_val_sub = dv_sub.transform(val_dicts_sub)

    model_sub = LogisticRegression(solver='liblinear', C=1.0, max_iter=1000, random_state=42)
    model_sub.fit(X_train_sub, y_train)

    acc_sub = (model_sub.predict(X_val_sub) == y_val).mean()
    diff = original_accuracy - acc_sub
    print(f"Excluding {feature:<25} -> Acc: {acc_sub:.6f}, Difference: {diff:.6f}")

"""## Question 6: Regularization Parameter C tuning"""

for c in [0.000001, 0.00001, 0.0001, 0.001]:
    model_c = LogisticRegression(solver='liblinear', C=c, max_iter=1000, random_state=42)
    model_c.fit(X_train, y_train)
    acc_c = (model_c.predict(X_val) == y_val).mean()
    print(f"C = {c:<8} -> Accuracy: {acc_c:.3f} (Exact: {acc_c:.6f})")